export function npcLine(trigger: NpcTrigger, rng: Rng, ctx: { theme?: Theme; hour?: number } = {}): string {
  if (trigger === 'post' && ctx.theme && THEME_LINES[ctx.theme] && rng.next() < 0.7) return pick(rng, THEME_LINES[ctx.theme]!);
  if (trigger === 'welcome' && ctx.hour !== undefined) {
    if (ctx.hour < 5) return pick(rng, ['夜ふかし？ 一緒に潜ろう', 'こんな時間まで起きてるの？']);
    if (ctx.hour < 10) return pick(rng, ['おはよう！ 夢、見た？', 'おはよう。昨日の夜もがんばって潜ったよ']);
    if (ctx.hour >= 22) return pick(rng, ['今日もおつかれさま', '寝てる間も潜っておくね。おやすみ']);
  }
  return pick(rng, LINES[trigger]);
}

